// screen: 4 Guess? 37
// screen: 5 Got it in 3 tries
char buf[8];
int main(void)
{
    int secret = 37, tries = 0, g;
    cls();
    do {
        print("Guess? ");
        gets(buf, sizeof buf);
        g = atoi(buf);
        tries++;
        if (g < secret)
            puts("Too low");
        else if (g > secret)
            puts("Too high");
    } while (g != secret);
    printf("Got it in %d tries\n", tries);
    return tries;
}

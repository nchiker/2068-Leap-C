int d[8] = { 34, 7, 23, 32, 5, 62, 12, 48 };
int sort(int *a, int n)
{
    int i, t, swaps = 0, swapped = 1;
    while (swapped) {
        swapped = 0;
        for (i = 0; i < n - 1; i++) {
            if (a[i] > a[i + 1]) {
                t = a[i];
                a[i] = a[i + 1];
                a[i + 1] = t;
                swapped = 1;
                swaps++;
            }
        }
    }
    return swaps;
}

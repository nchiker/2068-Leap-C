#!/usr/bin/env python3
"""Generate the float operator and conversion cases in tests/float/gen/ (Phase 8; spec.md 4.3, 4.9).

The expected results come from tools/fpmodel.py, the bit-exact model of the float core: the floating
constants as the ROM's decimal conversion makes them, then the operation on the two values (left,
right), rounded as the core rounds. Each case evaluates its operator in every code shape the compiler
has for floats, so every path of CX_FBINOP, CG_FLOAD and CG_FSTORE runs: globals and locals (deferred
left operands: the right one pushed, the left loaded, the operation reversed), parameters, a constant
on either side and both (folded at compile time), function results (a resident left operand in its
stack slot), a struct member and a pointer's target, an int, unsigned or char operand on either side
(converted at run time), an array element as the destination. Float results go to r[] and
comparisons to c[]; the case checks both byte for byte after the run (`// mem:`).

Usage: gen_floattests.py [--out tests/float/gen]   (rewrites the directory's generated cases)
"""
import argparse
import glob
import os

import fpmodel as F

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PAIRS = [("1.5", "2.25"), ("-7.125", "0.5"), ("1234.5678", "-0.001"), ("3e10", "7e-3"), ("0.1", "0.3"),
         ("-2.5e-20", "-4e15"), ("100", "100.0"), ("0", "-1.75"), ("65535.5", "1e-5"), ("6.02e23", "-6.02e23")]
INTS = [("int", 7), ("int", -300), ("unsigned", 40000), ("char", 200)]
CMPS = [("<", "lt"), (">", "gt"), ("<=", "le"), (">=", "ge"), ("==", "eq"), ("!=", "ne")]
ARITH = [("+", "add"), ("-", "sub"), ("*", "mul"), ("/", "div")]


def lit(t):
    """A floating constant as the compiler makes it: a leading minus is the unary operator, folded."""
    if t.startswith("-"):
        return F.neg(lit(t[1:]))
    return F.atof(t + ";")[0]


def ival(ctype, v):
    if ctype == "unsigned":
        return F.fru(v)
    if ctype == "char":
        return F.fri(v & 0xFF)
    return F.fri(v)


def hexs(bs):
    return "".join(b.hex() for b in bs)


def init(decl, items, per=5):
    """An initialised array declaration over several lines."""
    out = [decl + " = {"]
    for i in range(0, len(items), per):
        out.append("    " + ", ".join(items[i:i + per]) + ("," if i + per < len(items) else ""))
    return out + ["};"]


def mem(name, hx, chunk=80):
    """`// mem:` lines for the hex string hx (the editor's lines are at most 127 characters)."""
    out = []
    for i in range(0, len(hx), chunk):
        out.append("// mem: %s+%d %s" % (name, i // 2, hx[i:i + chunk]))
    return out


def arith_case(sym, name, k, a, b, it, iv):
    A, B = lit(a), lit(b)
    I = ival(it, iv)
    want = lambda x, y: F.binop(sym, x, y)
    shapes = [
        ("ga %s gb" % sym, A, B), ("la %s lb" % sym, A, B), ("fp(ga, gb)", A, B), ("ga %s %s" % (sym, b), A, B),
        ("%s %s gb" % (a, sym), A, B), ("%s %s %s" % (a, sym, b), A, B), ("fr(ga) %s fr(gb)" % sym, A, B),
        ("fr(ga) %s lb" % sym, A, B), ("sv.x %s *p" % sym, A, B), ("iv %s gb" % sym, I, B),
        ("ga %s iv" % sym, A, I), ("fr(ga) %s iv" % sym, A, I), ("iv %s fr(gb)" % sym, I, B),
    ]
    results = []
    for _, x, y in shapes:
        results.append(want(x, y))
    lines = ["// generated by tools/gen_floattests.py: float %s, %s %s %s, with %s %d" % (name, a, sym, b, it, iv),
             "// expect: exit 0"] + mem("r", hexs(results)) + [
             "struct s { int pad; float x; } sv = { 9, %s };" % a,
             "float ga = %s;" % a,
             "float gb = %s;" % b,
             "float r[%d];" % len(shapes),
             "%s iv = %d;" % (it, iv),
             "float fr(float x) { return x; }",
             "float fp(float x, float y) { return x %s y; }" % sym,
             "int main(void)",
             "{",
             "    float la;",
             "    float lb;",
             "    float *p;",
             "    int n;",
             "    la = %s;" % a,
             "    lb = %s;" % b,
             "    p = &gb;",
             "    n = 0;"]
    for expr, _, _ in shapes:
        lines.append("    r[n++] = %s;" % expr)
    lines += ["    return 0;", "}"]
    return lines


def cmp_case(k, a, b):
    A, B = lit(a), lit(b)
    vals = []
    exprs = []
    for sym, _ in CMPS:
        c = F.binop("cmp", A, B)
        truth = {"<": c < 0, ">": c > 0, "<=": c <= 0, ">=": c >= 0, "==": c == 0, "!=": c != 0}[sym]
        for e in ("ga %s gb" % sym, "%s %s gb" % (a, sym), "fr(ga) %s fr(gb)" % sym, "la %s %s" % (sym, b)):
            exprs.append(e)
            vals.append(int(truth))
        # the comparison as a condition (jumps) rather than a value
        exprs.append("(ga %s gb) ? 5 : 6" % sym)
        vals.append(5 if truth else 6)
    lines = ["// generated by tools/gen_floattests.py: float comparisons of %s and %s" % (a, b),
             "// expect: exit 0"] + mem("c", "".join("%02x%02x" % (v & 255, v >> 8 & 255) for v in vals)) + [
             "float ga = %s;" % a,
             "float gb = %s;" % b,
             "int c[%d];" % len(vals),
             "float fr(float x) { return x; }",
             "int main(void)",
             "{",
             "    float la;",
             "    int n;",
             "    la = %s;" % a,
             "    n = 0;"]
    for e in exprs:
        lines.append("    c[n++] = %s;" % e)
    lines += ["    return 0;", "}"]
    return lines


def conv_case():
    """Float to int, unsigned, char, signed char and back, at run time and in constants."""
    fl = ["0.0", "0.75", "-0.75", "1.5", "-1.5", "255.9", "-128.5", "32767.0", "-32768.0", "40000.25", "65535.0",
          "123456.0", "1e-30"]
    ints = []
    for t in fl:
        v = F.toi(lit(t))
        ints.append(v)
    back = [0, 1, -1, 127, -128, 255, 32767, -32767, 12345, -1000]
    ub = [0, 1, 32768, 40000, 65535]
    cb = [0, 1, 127, 128, 255]
    lines = (["// generated by tools/gen_floattests.py: conversions between float and the integer types",
              "// expect: exit 0"] + mem("ri", "".join("%02x%02x" % (v & 255, v >> 8) for v in ints)) +
             mem("rc", "".join("%02x" % (v & 255) for v in ints)) +
             mem("rk", "".join("%02x%02x" % (v & 255, v >> 8) for v in ints)) +
             mem("rf", hexs([F.fri(v) for v in back])) + mem("ru", hexs([F.fru(v) for v in ub])) +
             mem("rs", hexs([F.fri(v - 256 if v > 127 else v) for v in cb] + [F.fri(v) for v in cb])) +
             mem("kf", hexs([F.fri(v) for v in back])) + [
             ] + init("float fl[%d]" % len(fl), fl) + [
             "int ri[%d];" % len(fl),
             "char rc[%d];" % len(fl)] + init("int rk[%d]" % len(fl), ["(int)%s" % t for t in fl]))
    lines += ["float rf[%d];" % len(back), "float ru[%d];" % len(ub), "float rs[%d];" % (2 * len(cb)),
              "float kf[%d] = { %s };" % (len(back), ", ".join(str(v) for v in back)),
              "int ib[%d] = { %s };" % (len(back), ", ".join(str(v) for v in back)),
              "unsigned ub[%d] = { %s };" % (len(ub), ", ".join("%du" % v for v in ub)),
              "signed char sb[%d] = { %s };" % (len(cb), ", ".join(str(v - 256 if v > 127 else v) for v in cb)),
              "char cb[%d] = { %s };" % (len(cb), ", ".join(str(v) for v in cb)),
              "int main(void)", "{", "    int i;",
              "    for (i = 0; i < %d; i++) {" % len(fl), "        ri[i] = fl[i];", "        rc[i] = fl[i];", "    }",
              "    for (i = 0; i < %d; i++)" % len(back), "        rf[i] = ib[i];",
              "    for (i = 0; i < %d; i++) {" % len(ub), "        ru[i] = ub[i];", "        rs[i] = sb[i];",
              "        rs[i + %d] = cb[i];" % len(cb), "    }",
              "    return 0;", "}"]
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "tests", "float", "gen"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    for f in glob.glob(os.path.join(a.out, "*.c")):
        os.remove(f)
    n = 0
    for sym, name in ARITH:
        for k, (x, y) in enumerate(PAIRS):
            if sym == "/" and F.value(lit(y)) == 0:
                continue
            it, iv = INTS[k % len(INTS)]
            try:
                lines = arith_case(sym, name, k, x, y, it, iv)
            except F.FloatError:
                continue                            # (an overflow: the runtime-error cases cover it)
            open(os.path.join(a.out, "%s_%02d.c" % (name, k)), "w").write("\n".join(lines) + "\n")
            n += 1
    for k, (x, y) in enumerate(PAIRS + [("2.5", "2.5"), ("-1", "-1.0"), ("0", "-0.0")]):
        open(os.path.join(a.out, "cmp_%02d.c" % k), "w").write("\n".join(cmp_case(k, x, y)) + "\n")
        n += 1
    open(os.path.join(a.out, "conv.c"), "w").write("\n".join(conv_case()) + "\n")
    n += 1
    print("gen_floattests: %d cases in %s" % (n, os.path.relpath(a.out, ROOT)))


if __name__ == "__main__":
    main()

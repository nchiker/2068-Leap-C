#!/usr/bin/env python3
"""The release assets (Phase 11, the public beta): two zips in build/release/, built from build/ (make build, make kit).

  leapc-VERSION-emulators.zip      the emulator pack: the ROM images (roms/: leapc_zesarux.bin for ZEsarUX,
                                   leapc_home.bin and leapc_exrom.bin for Fuse and TSRun), the documents' example
                                   programs (tapes/examples/: exNN from docs/EXAMPLES.md, ugNN from docs/USER_GUIDE.md,
                                   as tests/doc/ holds them) and the hardware check programs (tapes/checks/, the kit's)
                                   as .tap and .tzx, the shapes library's tapes and source (libs/), the beta's guides
                                   (docs/: EMULATORS, USER_GUIDE, BETA_TESTING, EXAMPLES, and their pictures), LICENSE,
                                   NOTICE, TAPES.md (what each tape is) and SHA256SUMS (every file)
  leapc-VERSION-hardware-kit.zip   build/kit (EPROM images with Intel HEX, the tapes as .tap/.tzx/.wav, the checklist,
                                   the emulators' results, CHECKSUMS.txt), LICENSE and NOTICE
  SHA256SUMS                       the two zips

The leapc_exrom.dck cartridge is left out: ZEsarUX refuses it (it takes only DOCK-bank cartridges; docs/EMULATORS.md
section 10) and it was never tested elsewhere. The zips are reproducible: sorted entries, fixed times and modes, so
two clean builds give the same zips (and their ROM images are make repro's).

Usage: release.py [--version 1.0.0-beta.1]"""
import argparse
import hashlib
import os
import re
import shutil
import sys
import zipfile

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import c2tape           # noqa: E402
import tapes            # noqa: E402

ROOT = os.path.dirname(HERE)
BUILD = os.path.join(ROOT, "build")
OUT = os.path.join(BUILD, "release")
STAMP = (2026, 10, 22, 0, 0, 0)                 # every zip entry's time (reproducible zips)
DOCS = ["EMULATORS.md", "USER_GUIDE.md", "BETA_TESTING.md", "EXAMPLES.md"]
EXAMPLE_SETS = [("examples_", "ex", "example", "docs/EXAMPLES.md"), ("user_guide_", "ug", "guide", "docs/USER_GUIDE.md")]
CHECKS = [("h1_hello", "H1", "hello"), ("h2_keys", "H2", "keys"), ("h3_hz60", "H3", "hz60"), ("h4_cont1", "H4", "cont1"),
          ("h5_cont4", "H5", "cont4"), ("h6_float", "H6", "float"), ("h7_sound", "H7", "sound"), ("h8_brk", "H8", "brk"),
          ("h9_tapedata", "H9", "tapedata"), ("h10_soak", "H10", "soak"), ("h11_libcheck", "H11", "libcheck")]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def section_of(doc, line):
    """The heading above `line` of `doc` (its ## or ### title)."""
    title = ""
    for i, l in enumerate(open(os.path.join(ROOT, doc), encoding="utf-8").read().split("\n"), 1):
        if i > line:
            break
        if l.startswith("## ") or l.startswith("### "):
            title = l.lstrip("#").strip()
    return title


def write_zip(path, top, files):
    """files: {name inside `top`/: bytes}, written sorted with fixed times and modes."""
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name in sorted(files):
            info = zipfile.ZipInfo("%s/%s" % (top, name), STAMP)
            info.external_attr = 0o644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, files[name])


def emulator_pack(version):
    files = {}
    for f in ("leapc_home.bin", "leapc_exrom.bin", "leapc_zesarux.bin"):
        files["roms/" + f] = open(os.path.join(BUILD, f), "rb").read()
    rows = ["# The tapes in this pack", "",
            "Each program tape loads with `LOAD \"\"` (or `LOAD \"name\"` with the tape name below); "
            "a library tape with `LIB \"shapes\"`. docs/EMULATORS.md section 7 says how to play a tape in each emulator. "
            "The first lines of an example (`// expect:`, `// screen:`) say what it should show when it is RUN.", "",
            "## Examples (tapes/examples/)", "", "| File | Tape name | From | Needs |", "|---|---|---|---|"]
    docdir = os.path.join(ROOT, "tests", "doc")
    for prefix, stem, tname, _ in EXAMPLE_SETS:
        for p in sorted(f for f in os.listdir(docdir) if f.startswith(prefix)):
            n = p[len(prefix):].split(".")[0]
            text = open(os.path.join(docdir, p), encoding="utf-8").read()
            m = re.search(r"// Generated by tools/docexamples.py from (\S+) line (\d+)", text)
            src = "%s, %s" % (m.group(1).split("/")[-1], section_of(m.group(1), int(m.group(2)))) if m else p
            lib = re.search(r"^// library: (\S+)", text, re.M)
            blocks = c2tape.program_blocks(text, tname + n)
            files["tapes/examples/%s%s.tap" % (stem, n)] = tapes.tap(blocks)
            files["tapes/examples/%s%s.tzx" % (stem, n)] = tapes.tzx(blocks)
            rows.append("| `%s%s.tap`, `.tzx` | `%s%s` | %s | %s |" % (
                stem, n, tname, n, src, ("`LIB \"%s\"` first" % lib.group(1)) if lib else ""))
    rows += ["", "## Hardware check programs (tapes/checks/)", "",
             "The programs of docs/HARDWARE_CHECKLIST.md (in the hardware kit); they run in an emulator too.", "",
             "| File | Tape name | Check |", "|---|---|---|"]
    kit = os.path.join(BUILD, "kit", "tapes")
    for stem, cid, tname in CHECKS:
        for ext in (".tap", ".tzx"):
            files["tapes/checks/" + stem + ext] = open(os.path.join(kit, stem + ext), "rb").read()
        rows.append("| `%s.tap`, `.tzx` | `%s` | %s%s |" % (stem, tname, cid, " (needs `LIB \"shapes\"` first)" if cid == "H11" else ""))
    rows += ["", "## The library (libs/)", "", "| File | What it is |", "|---|---|",
             "| `shapes.tap`, `.tzx` | the example library: `LIB \"shapes\"` adds `circle()`, `box()`, `isqrt()` |",
             "| `shapes.asm` | its source (built with tools/lib2tape.py and include/leapc_lib.inc from the repository) |", ""]
    for ext in (".tap", ".tzx"):
        files["libs/shapes" + ext] = open(os.path.join(BUILD, "libs", "shapes" + ext), "rb").read()
    files["libs/shapes.asm"] = open(os.path.join(ROOT, "libs", "shapes.asm"), "rb").read()
    files["TAPES.md"] = "\n".join(rows).encode()
    for d in DOCS:
        files["docs/" + d] = open(os.path.join(ROOT, "docs", d), "rb").read()
    for img in sorted(os.listdir(os.path.join(ROOT, "docs", "images"))):
        files["docs/images/" + img] = open(os.path.join(ROOT, "docs", "images", img), "rb").read()
    for f in ("LICENSE", "NOTICE"):
        files[f] = open(os.path.join(ROOT, f), "rb").read()
    files["README.txt"] = ("Leap-C %s: the emulator pack\n\n"
                           "Start with docs/EMULATORS.md (setting up Fuse, ZEsarUX or TSRun), then docs/USER_GUIDE.md.\n"
                           "docs/BETA_TESTING.md says what to test and how to report it.\n"
                           "roms/  the ROM images; tapes/  programs to LOAD (TAPES.md lists them); libs/  the shapes library.\n"
                           "Links in the documents to other files of the project point into the repository:\n"
                           "https://github.com/nchiker/2068-Leap-C\n"
                           "SHA256SUMS lists every file's SHA-256. Licence: LICENSE (MIT) and NOTICE.\n" % version).encode()
    files["SHA256SUMS"] = "".join("%s  %s\n" % (sha(files[n]), n) for n in sorted(files)).encode()
    return files


def kit_pack():
    files = {}
    kit = os.path.join(BUILD, "kit")
    for d, _, fs in os.walk(kit):
        for f in fs:
            p = os.path.join(d, f)
            files[os.path.relpath(p, kit).replace(os.sep, "/")] = open(p, "rb").read()
    for f in ("LICENSE", "NOTICE"):
        files[f] = open(os.path.join(ROOT, f), "rb").read()
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", default="1.0.0-beta.1")
    a = ap.parse_args()
    for need in ("leapc_home.bin", "libs/shapes.tzx", "kit/CHECKSUMS.txt"):
        if not os.path.exists(os.path.join(BUILD, need)):
            sys.exit("release: build/%s is missing (make build and make kit first)" % need)
    shutil.rmtree(OUT, ignore_errors=True)
    os.makedirs(OUT)
    names = []
    for kind, files in (("emulators", emulator_pack(a.version)), ("hardware-kit", kit_pack())):
        top = "leapc-%s-%s" % (a.version, kind)
        write_zip(os.path.join(OUT, top + ".zip"), top, files)
        names.append(top + ".zip")
        print("release: %s.zip, %d files" % (top, len(files)))
    sums = "".join("%s  %s\n" % (sha(open(os.path.join(OUT, n), "rb").read()), n) for n in names)
    open(os.path.join(OUT, "SHA256SUMS"), "w").write(sums)
    print(sums, end="")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Write the HOME symbols that the EXROM may call (src/rom/home_exports.txt) as an sjasmplus
include, from the HOME build's symbol file. Usage: gen_exports.py HOME.sym NAMES.txt OUT.inc"""
import re
import sys


def main():
    sym, names, out = sys.argv[1:4]
    table = {}
    for line in open(sym):
        m = re.match(r"([A-Za-z_][A-Za-z0-9_.]*):\s+EQU\s+0x([0-9A-F]+)", line, re.I)
        if m:
            table[m.group(1)] = int(m.group(2), 16)
    wanted = [n.split("#")[0].strip() for n in open(names)]
    wanted = [n for n in wanted if n]
    missing = [n for n in wanted if n not in table]
    if missing:
        sys.exit("gen_exports: not in %s: %s" % (sym, ", ".join(missing)))
    bad = [n for n in wanted if table[n] >= 0x4000]
    if bad:
        sys.exit("gen_exports: not HOME ROM addresses: %s" % ", ".join(bad))
    with open(out, "w") as f:
        f.write("; generated by tools/gen_exports.py from %s -- do not edit\n" % sym)
        for n in wanted:
            f.write("%-28s EQU $%04X\n" % (n, table[n]))


if __name__ == "__main__":
    main()

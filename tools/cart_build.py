#!/usr/bin/env python3
"""The runtime cartridge's build constants (make cart; docs/milestones/M12-cart.md).

Writes build/cart/cart_exrom.inc for src/cart/cart.asm: CART_IDENTITY, the CRC-16/CCITT of the release HOME then
EXROM images (build/leapc_home.bin, build/leapc_exrom.bin; 0 bytes in either), and the release EXROM addresses the
cartridge calls (from build/leapc_exrom.sym: the cartridge carries that EXROM unchanged).

Usage: cart_build.py [--identity]   (--identity: print the identity only)"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, "build")
OUT = os.path.join(BUILD, "cart", "cart_exrom.inc")
EXROM_NAMES = {"CART_X_SH_RUN_COMPILED": "SH_RUN.compiled", "CART_X_SH_SHOW_MESSAGE": "SH_SHOW_MESSAGE"}


def crc16(data, crc=0xFFFF):
    """CRC-16/CCITT-FALSE: polynomial $1021, initial $FFFF, MSB first, no final xor."""
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def identity(build=BUILD):
    return crc16(open(os.path.join(build, "leapc_home.bin"), "rb").read() +
                 open(os.path.join(build, "leapc_exrom.bin"), "rb").read())


def syms(path):
    out = {}
    for line in open(path):
        m = re.match(r"([A-Za-z_][A-Za-z0-9_.]*):\s+EQU\s+0x([0-9A-F]+)", line, re.I)
        if m:
            out[m.group(1)] = int(m.group(2), 16)
    return out


def main():
    ident = identity()
    if "--identity" in sys.argv:
        print("$%04X" % ident)
        return
    s = syms(os.path.join(BUILD, "leapc_exrom.sym"))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("; generated by tools/cart_build.py from build/leapc_*.bin and build/leapc_exrom.sym -- do not edit\n")
        f.write("CART_IDENTITY %s EQU $%04X     ; CRC-16/CCITT of the release HOME + EXROM\n" % (" " * 12, ident))
        for name, label in EXROM_NAMES.items():
            if not 0xC000 <= s[label] < 0xE000:
                sys.exit("cart_build: %s is not an EXROM address" % label)
            f.write("%-28s EQU $%04X     ; %s (release EXROM)\n" % (name, s[label], label))
    print("cart_build: identity $%04X; %s" % (ident, os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()

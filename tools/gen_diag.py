#!/usr/bin/env python3
"""Build the EXROM's diagnostic message table (Phase 6, src/shell/diag.asm) from include/leapc_errors.inc.

Every compile error (E_*) and runtime error (RTE_*, except BREAK) line of leapc_errors.inc carries its
message as a quoted text. The table is word-compressed: each distinct word is stored once (DG_WORDS,
the last character with bit 7 set) and each message is the 1-based numbers of its words in DG_WORDS
(DG_MSGS: [word]...[word | $80], in key order, ended by DG_END). A message's key is the previous
message's + 1, unless DG_KEY and its key come first. A compile error's key is its number; a runtime
error's is DG_RT + its number.

Usage: gen_diag.py OUT.inc        (writes the assembler include)
As a module: messages() -> {("E", n): text, ("RT", n): text}; report(kind, n) -> the report text.
"""
import os
import re
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "include", "leapc_errors.inc")
DG_RT = 0x80                      # runtime messages' keys: DG_RT + the error number
ROW = 32                          # the report row's width


def messages(path=SRC):
    out = {}
    for line in open(path):
        m = re.match(r"\s*(E|RTE)_[A-Z0-9_]+\s+EQU\s+(\d+)\s*;\s*\"([^\"]+)\"", line)
        if m:
            kind = "E" if m.group(1) == "E" else "RT"
            out[(kind, int(m.group(2)))] = m.group(3)
    return out


def report(kind, n, msgs=None):
    """The text the shell shows on the report row for error n."""
    msgs = msgs or messages()
    if kind == "RT" and n == 5:
        return "BREAK"
    return ("ERROR %d: %s" if kind == "E" else "RUNTIME ERROR %d: %s") % (n, msgs[(kind, n)])


def build(msgs):
    items = sorted(((n if kind == "E" else DG_RT + n), text) for (kind, n), text in msgs.items()
                   if not (kind == "RT" and n == 5))
    for key, text in items:
        assert 0 < key < 256, key
        assert re.fullmatch(r"[A-Z0-9-]+( [A-Z0-9-]+)*", text), "message %r: upper case words, single spaces" % text
    for (kind, n), text in msgs.items():
        assert len(report(kind, n, msgs)) <= ROW, "%r is longer than the report row" % report(kind, n, msgs)
    count = Counter(w for _, t in items for w in t.split())
    words = sorted(count, key=lambda w: (-count[w], w))           # deterministic order
    assert len(words) <= 0x7D, "too many distinct words"     # (word | $80 stays below DG_END)
    index = {w: i for i, w in enumerate(words)}
    lines = ["; build/diag_text.inc -- generated by tools/gen_diag.py from include/leapc_errors.inc: do not edit",
             "DG_RT           EQU $%02X           ; a runtime error's message key: DG_RT + its number" % DG_RT,
             "DG_KEY          EQU $FF           ; the next message's key follows (else: the previous key + 1)",
             "DG_END          EQU $FE           ; the end of DG_MSGS",
             "; messages in key order: [DG_KEY key] [word]...[last word | $80]; words count from 1", "DG_MSGS:"]
    prev = None
    for key, text in items:
        ix = [index[w] + 1 for w in text.split()]
        ix[-1] |= 0x80
        head = "" if prev is not None and key == prev + 1 else "DG_KEY, %d, " % key
        lines.append("    DB   %-40s ; %d %s" % (head + ", ".join("$%02X" % i for i in ix), key, text))
        prev = key
    lines += ["    DB   DG_END", "; words: the last character with bit 7 set", "DG_WORDS:"]
    for w in words:
        lines.append('    DB   "%s", "%s" | $80' % (w[:-1], w[-1]) if len(w) > 1 else '    DB   "%s" | $80' % w)
    return "\n".join(lines).replace('DB   "", ', "DB   ") + "\n"


def main():
    out = sys.argv[1]
    text = build(messages())
    old = open(out).read() if os.path.exists(out) else None
    if text != old:
        with open(out, "w") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())

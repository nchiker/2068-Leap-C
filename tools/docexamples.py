"""Leap-C documentation examples as corpus cases (Phase 8, project_plan.md section 10).

Every fenced ```c block in the documents below (and in each part of docs/manual/) whose text holds at least one expectation line
(`// expect: ...`, the executable corpus's syntax: tools/exectest.py) is a test. Each becomes
tests/doc/<document>_<NN>.c, a generated file that ends with the document and line it comes from
(last, so that the example's line numbers are the test's), and runs with the executable corpus
(the direct path, the shell's RUN path and the canary). Blocks without an expectation (prototypes,
fragments) are not tests.

Usage: docexamples.py            regenerate tests/doc/ from the documents
       docexamples.py --check    fail if tests/doc/ differs from the documents (make check)"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "tests", "doc")
DOCS = ["README.md", "spec.md", "docs/EXAMPLES.md", "docs/USER_GUIDE.md", "docs/EMULATORS.md",
        "docs/BETA_TESTING.md"]      # (Phase 11: the beta's guides)
DOCS += sorted(os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(ROOT, "docs", "manual", "*.md")))
                                    # the user's manual, part by part
FOOTER = "// Generated by tools/docexamples.py from %s line %d: edit the document, not this file.\n"


def examples():
    """{file name: text} of every example in DOCS."""
    out = {}
    for doc in DOCS:
        path = os.path.join(ROOT, doc)
        if not os.path.exists(path):
            continue
        stem = re.sub(r"[^a-z0-9]+", "_", os.path.splitext(os.path.basename(doc))[0].lower())
        if doc.startswith("docs/manual/"):
            stem = "manual_" + stem
        lines = open(path, encoding="utf-8").read().split("\n")
        k, i = 0, 0
        while i < len(lines):
            if lines[i].strip() != "```c":
                i += 1
                continue
            start = i + 1
            j = start
            while j < len(lines) and lines[j].strip() != "```":
                j += 1
            body = lines[start:j]
            if any(l.strip().startswith("// expect:") for l in body):
                k += 1
                out["%s_%02d.c" % (stem, k)] = "\n".join(body) + "\n" + FOOTER % (doc, start + 1)
            i = j + 1
    return out


def main():
    want = examples()
    have = {os.path.basename(p): open(p, encoding="latin-1").read()
            for p in glob.glob(os.path.join(OUT, "*.c"))}
    if "--check" in sys.argv:
        bad = sorted(n for n in set(want) | set(have) if want.get(n) != have.get(n))
        if bad:
            print("docexamples: tests/doc/ is out of date (%s); run tools/docexamples.py" % ", ".join(bad))
            sys.exit(1)
        print("docexamples: %d examples, tests/doc/ up to date" % len(want))
        return
    os.makedirs(OUT, exist_ok=True)
    for n in set(have) - set(want):
        os.remove(os.path.join(OUT, n))
    for n, text in want.items():
        if have.get(n) != text:
            with open(os.path.join(OUT, n), "w", encoding="latin-1") as f:
                f.write(text)
    print("docexamples: %d examples in tests/doc/" % len(want))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate the switch test cases of tests/stmt/gen (Phase 2): random case sets that make sparse
and dense tables (stmt.asm SW_TABLE), with int, unsigned and char controlling values, each checked
on its case values, their neighbours, values far outside and the extremes of the type.

The expected results come from this model, not from the ROM: a switch jumps to the case whose
value equals the controlling value converted to its promoted type (int or unsigned; char is
unsigned and promotes to int), else to the default, else past the switch (C89 6.6.4.2).

Usage: gen_stmttests.py [OUTDIR]   (default tests/stmt/gen; the files are committed)"""
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def table_kind(values):
    """The table SW_TABLE builds: dense when highest - lowest <= 2 n - 3 (signed order)."""
    s = sorted(v - 65536 if v >= 32768 else v for v in values)
    return "dense" if s and s[-1] - s[0] <= 2 * len(s) - 3 else "sparse"


def wrap(head, items):
    """An initialised array, its items on lines of at most 100 characters (the editor's limit is 127)."""
    out, line = [head], "   "
    for i, it in enumerate(items):
        piece = " " + it + ("," if i + 1 < len(items) else "")
        if len(line) + len(piece) > 100:
            out.append(line)
            line = "   "
        line += piece
    out += [line, "};"]
    return out


def case(rnd, name, typ, values, default):
    """One test: f(v) returns the case's index + 1, the default 99, or 0 past the switch."""
    lit = (lambda v: "%du" % v) if typ == "unsigned" else (lambda v: "%d" % (v - 65536 if v >= 32768 else v))
    if typ == "char":
        lit = lambda v: "%d" % v
    lines = ["// Generated by tools/gen_stmttests.py: a switch on %s with %d cases (%s table)%s." % (
        typ, len(values), table_kind(values), ", a default" if default else ""), "// expect: exit 0",
        "int f(%s v)" % typ, "{", "    switch (v) {"]
    order = list(range(len(values)))
    rnd.shuffle(order)
    for i in order:
        lines.append("    case %s: return %d;" % (lit(values[i]), i + 1))
        if default and i == order[len(order) // 2]:
            lines.append("    default: return 99;")
    lines += ["    }", "    return 0;", "}"]
    mod = 256 if typ == "char" else 65536
    probes = set()
    for v in values:
        probes.update(((v - 1) % mod, v, (v + 1) % mod))
    probes.update((0, mod - 1, 1, mod // 2, mod // 2 - 1))
    for _ in range(6):
        probes.add(rnd.randrange(mod))
    probes = sorted(probes)
    want = [values.index(p) + 1 if p in values else (99 if default else 0) for p in probes]
    plit = (lambda v: "%du" % v) if typ == "unsigned" else lit
    lines += wrap("%s probe[%d] = {" % (typ, len(probes)), [plit(p) for p in probes])
    lines += wrap("char want[%d] = {" % len(want), [str(w) for w in want])
    lines += ["int main(void)", "{", "    int i;",
              "    for (i = 0; i < %d; i++)" % len(probes),
              "        if (f(probe[i]) != want[i]) return i + 1;", "    return 0;", "}"]
    return name, "\n".join(lines) + "\n"


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "tests", "stmt", "gen")
    os.makedirs(out, exist_ok=True)
    rnd = random.Random(2068)
    cases = []
    for k in range(6):                                   # dense: runs with a few holes
        start = rnd.choice([-40, -5, 0, 1, 100, 32760, -32768])
        n = rnd.randrange(3, 30)
        vals = sorted(set((start + i) & 0xFFFF for i in range(n + n // 3) if rnd.random() < 0.85))[:n]
        cases.append(case(rnd, "dense_int_%d.c" % k, "int", vals, k % 2 == 0))
    for k in range(6):                                   # sparse: spread out
        n = rnd.randrange(2, 25)
        vals = sorted(set(rnd.randrange(65536) for _ in range(n)))
        cases.append(case(rnd, "sparse_int_%d.c" % k, "int", vals, k % 2 == 1))
    for k in range(4):                                   # unsigned, around 32768 and 65535
        base = rnd.choice([32760, 65530, 40000, 0])
        vals = sorted(set((base + rnd.randrange(12)) & 0xFFFF for _ in range(rnd.randrange(3, 10))))
        cases.append(case(rnd, "unsigned_%d.c" % k, "unsigned", vals, k % 2 == 0))
    for k in range(4):                                   # char
        vals = sorted(set(rnd.randrange(256) for _ in range(rnd.randrange(2, 20))))
        if k == 0:
            vals = list(range(48, 58))                   # the digits: dense
        cases.append(case(rnd, "char_%d.c" % k, "char", vals, k % 2 == 1))
    for name, text in cases:
        open(os.path.join(out, name), "w").write(text)
    print("%d cases in %s (%d dense, %d sparse)" % (
        len(cases), out, sum("dense table" in t for _, t in cases), sum("sparse table" in t for _, t in cases)))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""2068-Leap-C code-shape spike: assemble the workloads in each code form, run them on the
frozen V2 release ROM (and on two RST-patched experimental copies of it) in ZEsarUX through
2068-Leap's qharness, and record bytes, T-states, stack high-water and correctness.

Usage:  python3 run_spike.py [--port 10620] [--quick]
Needs:  spike/v2ref/build (tools/get_v2_ref.sh), sjasmplus, ~/2068-Leap/tools/qual/qharness.py,
        ~/ts2068-debug, ZEsarUX 13.0.  Writes spike/build/ and spike/results/."""
import argparse, json, os, shutil, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True     # never write a bytecode cache into the frozen V2 tree
sys.path.insert(0, os.path.join(os.environ.get("LEAPC_V2_REPO", os.path.expanduser("~/2068-Leap")), "tools/qual"))
from qharness import Machine, load_syms        # noqa: E402

V2REF = os.path.join(HERE, "v2ref")
BUILD = os.path.join(HERE, "build")
RESULTS = os.path.join(HERE, "results")
LOW_BASE = 0x5B00            # helpers ($5B00) + drivers ($5C00); micro frame and result table at $7E00
DRIVER_BASE = 0x5C00
MICRO_FRAME = 0x7E00
RESULT_TAB = 0x7E40
CANARY_LO, CANARY_HI = 0xF800, 0xFF00
SP_START = 0xFF00

ROM_NAMES = ["MATH_MULTIPLY16", "GFX_PUTCHAR", "PKG_NUM_TO_TEXT_SAFE", "BANK_PAGE_EXROM_IN",
             "BANK_PAGE_EXROM_OUT", "BANK_EXROM_DEPTH", "FRAMES"]

# ---- workload cases: id, function, args (C order), check ----
N_SUM, N_COPY, N_ASUM, N_PTS, N_FACT = 255, 256, 100, 20, 7
CASES = [
    ("sum", "SUM", [N_SUM]),
    ("copy", "COPY", ["DST", "SRC", N_COPY]),
    ("asum", "ASUM", [N_ASUM]),
    ("move", "MOVE", ["PTS", N_PTS, 3]),
    ("fact7", "FACT", [N_FACT]),
    ("fact20", "FACT", [20]),
    ("psvc", "PSVC", []),
    ("soak", "SOAK", []),
]

# ---- helper micro-benchmarks: id, code (between T0 and T1), rom configs where it is valid ----
MICRO = [
    ("ldl_inline", ["ld l,(ix+0)", "ld h,(ix+1)"], ("v2ref",)),
    ("ldl_call", ["call H_LDL", "db 0"], ("v2ref",)),
    ("ldl_rst", ["rst $08", "db 0"], ("rst",)),
    ("stl_inline", ["ld (ix+0),l", "ld (ix+1),h"], ("v2ref",)),
    ("stl_call", ["call H_STL", "db 0"], ("v2ref",)),
    ("stl_rst", ["rst $10", "db 0"], ("rst",)),
    ("ldi_inline", ["ld a,(hl)", "inc hl", "ld h,(hl)", "ld l,a"], ("v2ref",)),
    ("ldi_call", ["call H_LDI"], ("v2ref",)),
    ("ldi_rst", ["rst $28"], ("rst",)),
    ("sti_inline", ["ex de,hl", "ld (hl),e", "inc hl", "ld (hl),d", "ex de,hl"], ("v2ref",)),
    ("sti_call", ["call H_STI"], ("v2ref",)),
    ("sti_rst", ["rst $30"], ("rst",)),
    ("nop_call", ["call H_NOP"], ("v2ref",)),
    ("nop_rst", ["rst $28"], ("disp",)),
    ("cmp_inline", ["ld a,d", "xor $80", "ld d,a", "ld a,h", "xor $80", "ld h,a", "ex de,hl", "or a",
                    "sbc hl,de"], ("v2ref",)),
    ("cmp_call", ["call H_CMPLT"], ("v2ref",)),
    ("cmp_dispatch", ["rst $30", "db 0"], ("disp",)),
    ("frame_inline", ["call EL_A"], ("v2ref",)),          # empty function, 2 bytes of locals
    ("frame_call", ["call EL_C_CALL"], ("v2ref",)),
    ("frame_rst", ["call EL_C_RST"], ("rst",)),
    # EXROM trampoline cost: from V2's state (chunk 6 = EXROM, depth 1) page out and back in
    ("bank_round_trip", ["call BANK_PAGE_EXROM_OUT", "call BANK_PAGE_EXROM_IN"], ("v2ref",)),
]
EXTRA_FUNCS = """
EL_A:                       ; inline prologue/epilogue, N = 2
        push ix
        ld ix,-2
        add ix,sp
        ld sp,ix
        ld hl,0
        ld sp,ix
        pop bc
        pop ix
        ret
EL_A_END:
EL_C_CALL:
        call H_ENTER
        db 2
        ld hl,0
        call H_LEAVE
        db 2
EL_C_CALL_END:
EL_C_RST:
        rst $18
        db 2
        ld hl,0
        rst $20
        db 2
EL_C_RST_END:
"""

VARIANTS = {   # name: (FORM, HMODE, CODE_BASE, rom config)
    "A_C000": (0, 0, 0xC000, "v2ref"),
    "Ccall_C000": (1, 0, 0xC000, "v2ref"),
    "Crst_C000": (1, 1, 0xC000, "rst"),
    "Mrst_C000": (2, 1, 0xC000, "rst"),      # mixed: locals inline, other templates via RST helpers
    "A_8400": (0, 0, 0x8400, "v2ref"),       # code below chunk 6, EXROM left paged in
    "Crst_8400": (1, 1, 0x8400, "rst"),
}


def arg_src(a):
    return str(a) if isinstance(a, int) else a


def gen_driver(page_out):
    out = ["; generated by run_spike.py"]
    for i, (cid, fn, args) in enumerate(CASES + [("hazard", "HAZARD", [])]):
        out += ["T_%s:" % cid, "        im 1"]
        if page_out:
            out.append("        call BANK_PAGE_EXROM_OUT")
        out += ["DI_%s:" % cid, "        di", "T0_%s:" % cid]
        for a in reversed(args):
            out += ["        ld hl,%s" % arg_src(a), "        push hl"]
        out.append("        call %s" % fn)
        out += ["        pop bc"] * len(args)
        out += ["T1_%s:" % cid, "        ld (RESULT_TAB+%d),hl" % (2 * i), "        ei"]
        if page_out:
            out.append("        call BANK_PAGE_EXROM_IN")
        out += ["D_%s:" % cid, "        jr D_%s" % cid]
    for mid, code, _ in MICRO:
        out += ["M_%s:" % mid, "        ld ix,MICRO_FRAME", "        ld hl,MICRO_FRAME+8",
                "        ld de,MICRO_FRAME+16", "        di", "M0_%s:" % mid]
        out += ["        " + c for c in code]
        out += ["M1_%s:" % mid, "        jr M1_%s" % mid]
    out.append(EXTRA_FUNCS)
    return "\n".join(out) + "\n"


def assemble(name, form, hmode, base):
    d = os.path.join(BUILD, name)
    os.makedirs(d, exist_ok=True)
    S = load_syms(os.path.join(V2REF, "build", "test_basic.sym"))
    with open(os.path.join(d, "v2syms.inc"), "w") as f:
        for n in ROM_NAMES:
            f.write("%s EQU $%04X\n" % (n, S[n]))
        f.write("MICRO_FRAME EQU $%04X\nRESULT_TAB EQU $%04X\n" % (MICRO_FRAME, RESULT_TAB))
    with open(os.path.join(d, "driver.inc"), "w") as f:
        f.write(gen_driver(page_out=base >= 0xC000))
    data = base + 0x1000
    top = os.path.join(d, "spike.asm")
    asm = os.path.join(HERE, "asm")
    with open(top, "w") as f:
        f.write("""    DEVICE ZXSPECTRUM48
    INCLUDE "{d}/v2syms.inc"
    INCLUDE "{a}/templates.inc"
    ORG ${low:04X}
    INCLUDE "{a}/helpers.asm"
    ASSERT $ <= ${drv:04X}
    ORG ${drv:04X}
    INCLUDE "{d}/driver.inc"
DRIVER_END:
    ASSERT $ <= MICRO_FRAME
    ORG ${base:04X}
    INCLUDE "{a}/workloads.asm"
    ORG ${data:04X}
ARR_A:  ds 2*{na}
SRC:    ds {nc}
DST:    ds {nc}
PTS:    ds 5*{np}
PSVC_TXT: ds 16
SOAK_FAIL: ds 2
DATA_END:
    SAVEBIN "{d}/low.bin", ${low:04X}, DRIVER_END-${low:04X}
    SAVEBIN "{d}/code.bin", ${base:04X}, CODE_END-${base:04X}
""".format(d=d, a=asm, low=LOW_BASE, drv=DRIVER_BASE, base=base, data=data, na=N_ASUM, nc=N_COPY, np=N_PTS))
    r = subprocess.run(["sjasmplus", "-DFORM=%d" % form, "-DHMODE=%d" % hmode, "--nologo",
                        "--sym=" + os.path.join(d, "spike.sym"), "--lst=" + os.path.join(d, "spike.lst"), top],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("assembly failed for %s:\n%s%s" % (name, r.stdout, r.stderr))
    return load_syms(os.path.join(d, "spike.sym"))


def make_rom(cfg, vectors, syms):
    """Copy of the V2 release image with RST vectors replaced by `jp helper` (HOME offset = address)."""
    d = os.path.join(BUILD, "rom_" + cfg, "build")
    os.makedirs(d, exist_ok=True)
    img = bytearray(open(os.path.join(V2REF, "build", "ts2068rom_zesarux.bin"), "rb").read())
    for vec, helper in vectors.items():
        a = syms[helper]
        img[vec:vec + 3] = bytes([0xC3, a & 0xFF, a >> 8])
    open(os.path.join(d, "ts2068rom_zesarux.bin"), "wb").write(img)
    for s in ("test_basic.sym", "exrom.sym"):
        shutil.copy(os.path.join(V2REF, "build", s), d)
    return os.path.dirname(d)


class Runner:
    def __init__(self, m):
        self.m = m

    def load_low(self):
        """Helpers, drivers, micro frame, result table, stack canary: RAM that is always visible."""
        m = self.m
        m.write(LOW_BASE, open(os.path.join(self.dir, "low.bin"), "rb").read())
        m.write(RESULT_TAB, bytes(32))
        m.write(MICRO_FRAME, bytes(range(32)))
        m.write(CANARY_LO, b"\xA5" * (CANARY_HI - CANARY_LO))

    def load_high(self, vname, syms):
        """Code and data. Called once the driver has paged EXROM out: a ZRCP write to $C000-$DFFF
        while EXROM is paged in hits the ROM and is lost (found by this spike)."""
        m = self.m
        base = VARIANTS[vname][2]
        code = open(os.path.join(self.dir, "code.bin"), "rb").read()
        m.write(base, code)
        assert m.read(base, len(code)) == code, "code did not land in RAM at %04X" % base
        m.write(syms["ARR_A"], b"".join(struct.pack("<H", i) for i in range(N_ASUM)))
        self.src = bytes((i * 7 + 0x5A) & 0xFF for i in range(N_COPY))
        m.write(syms["SRC"], self.src)
        m.write(syms["DST"], bytes(N_COPY))
        m.write(syms["PTS"], b"".join(struct.pack("<hhB", i, 0, 0) for i in range(N_PTS)))
        m.write(syms["PSVC_TXT"], bytes(16))

    def run_to(self, pc, budget):
        m = self.m
        m.set_bps([pc])
        m.run(budget)
        return m.pc() == pc

    def depth(self, sp0):
        mem = self.m.read(CANARY_LO, CANARY_HI - CANARY_LO)
        low = next((CANARY_LO + i for i, b in enumerate(mem) if b != 0xA5), None)
        return None if low is None else sp0 - low

    def case(self, vname, syms, cid, ei=False, budget=6_000_000):
        m = self.m
        m.restore()
        self.dir = os.path.join(BUILD, vname)
        self.load_low()
        if ei:
            m.write(syms["DI_" + cid], b"\x00")
        m.setreg("SP", SP_START)
        m.setreg("PC", syms["T_" + cid])
        assert self.run_to(syms["T0_" + cid], 2_000_000), "did not reach T0"
        self.load_high(vname, syms)
        sp0 = m.regs()["SP"]
        f0 = m.w16(syms["FRAMES"])
        m.cmd("reset-tstates-partial")
        ok1 = self.run_to(syms["T1_" + cid], budget)
        t = int(m.cmd("get-tstates-partial").strip())
        f1 = m.w16(syms["FRAMES"])
        dep = self.depth(sp0)
        # verification data is read here, while chunk 6 is still RAM (the driver pages EXROM back in next)
        vdata = dict(dst=m.read(syms["DST"], N_COPY), pts=m.read(syms["PTS"], 5 * N_PTS),
                     txt=m.read(syms["PSVC_TXT"], 6), row0=m.screen_rows(nrows=1)[0]) if ok1 else {}
        ok2 = ok1 and self.run_to(syms["D_" + cid], 2_000_000)
        idx = [c[0] for c in CASES + [("hazard",)]].index(cid)
        res = m.w16(RESULT_TAB + 2 * idx)
        return dict(t=t, ok_run=ok1 and ok2, pc=m.pc(), result=res, stack=dep, frames=f1 - f0,
                    depth_after=m.read(syms["BANK_EXROM_DEPTH"], 1)[0], vdata=vdata)

    def micro(self, vname, syms, mid):
        m = self.m
        m.restore()
        self.dir = os.path.join(BUILD, vname)
        self.load_low()
        m.setreg("SP", SP_START)
        m.setreg("PC", syms["M_" + mid])
        assert self.run_to(syms["M0_" + mid], 100_000)
        m.cmd("reset-tstates-partial")
        ok = self.run_to(syms["M1_" + mid], 100_000)
        t = int(m.cmd("get-tstates-partial").strip())
        r = m.regs()
        return dict(t=t, ok=ok, bytes=syms["M1_" + mid] - syms["M0_" + mid], HL=r["HL"])

    def verify(self, cid, syms, r, base):
        v = r.pop("vdata", {})
        if not v:
            return False
        if cid == "sum":
            return r["result"] == sum(range(1, N_SUM + 1)) & 0xFFFF
        if cid == "copy":
            return v["dst"] == self.src
        if cid == "asum":
            return r["result"] == sum(range(N_ASUM))
        if cid == "move":
            raw = v["pts"]
            return all(struct.unpack_from("<hh", raw, 5 * i) == (i + 3, i + 3) for i in range(N_PTS))
        if cid.startswith("fact"):
            n = int(cid[4:])
            v = 1
            for k in range(2, n + 1):
                v = (v * k) & 0xFFFF
            return r["result"] == v
        if cid == "soak":
            return r["result"] == 0 and v["txt"] == b"12345\0" and r["frames"] > 500
        if cid == "psvc":
            # HL = BANK_EXROM_DEPTH as seen inside PSVC: 0 when the code runs with chunk 6 = RAM
            return (v["txt"] == b"12345\0" and v["row0"].startswith("C")
                    and r["result"] & 0xFF == (0 if base >= 0xC000 else 1))
        return None


BASIC = {   # id: (setup-only program or None, full program, expected value among the scalars)
    "sum": (None, ["n = 255", "s = 0", "FOR i = 1 TO n", "s = s + i", "NEXT i"], 32640),
    "copy": (None, ["FOR i = 0 TO 255", "POKE 28928 + i, PEEK(28672 + i)", "NEXT i"], None),
    "asum": (["DIM a(100)", "FOR i = 0 TO 99", "a(i) = i", "NEXT i"],
             ["DIM a(100)", "FOR i = 0 TO 99", "a(i) = i", "NEXT i",
              "t = 0", "FOR i = 0 TO 99", "t = t + a(i)", "NEXT i"], 4950),
    "move": (["DIM x(20)", "DIM y(20)", "FOR i = 0 TO 19", "x(i) = i", "NEXT i"],
             ["DIM x(20)", "DIM y(20)", "FOR i = 0 TO 19", "x(i) = i", "NEXT i",
              "dx = 3", "FOR i = 0 TO 19", "x(i) = x(i) + dx", "y(i) = y(i) + x(i)", "NEXT i"], None),
    "fact7": (None, ["r = 1", "CALL f(7)", "END", "PROC f(n):", "IF n > 1 THEN", "r = r * n",
                     "CALL f(n - 1)", "ENDIF", "ENDP"], 5040),
}


def basic_run(m, lines):
    """Compile + run a stored program from V2_RUN_STORED; T-states of the compile phase (to VM_RUN)
    and of the run phase (VM_RUN to the final key wait), interrupts on as in normal use."""
    S = m.S
    m.restore()
    m.write(28672, bytes((i * 7 + 0x5A) & 0xFF for i in range(256)))
    m.write(28928, bytes(256))
    m.put_store(lines)
    m.write(0xFF00, struct.pack("<H", S["V2_COMMAND_LOOP.loop"]))
    m.setreg("SP", 0xFF00)
    m.setreg("PC", S["V2_RUN_STORED"])
    m.cmd("reset-tstates-partial")
    m.set_bps([S["VM_RUN"]])
    m.run(50_000_000)
    assert m.pc() == S["VM_RUN"], "BASIC: VM_RUN not reached (compile error %d)" % m.read(S["COMPILE_ERROR_CODE"], 1)[0]
    tc = int(m.cmd("get-tstates-partial").strip())
    m.cmd("reset-tstates-partial")
    m.set_bps([S["IO_READ_KEY"], S["V2_COMMAND_LOOP.loop"], S["V2_SHOW_MESSAGE"]])
    m.run(400_000_000)
    tr = int(m.cmd("get-tstates-partial").strip())
    pc = m.pc()
    clean = pc == S["IO_READ_KEY"] and m.w16(m.regs()["SP"]) == S["V2_COMMAND_LOOP.loop"]
    ve = m.read(S["VM_ERROR_CODE"], 1)[0]
    return dict(t_compile=tc, t_run=tr, clean=clean, ve=ve)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=10620)
    ap.add_argument("--micro-only", action="store_true", help="helper micro-benchmarks only; merges into the results file")
    a = ap.parse_args()
    os.makedirs(RESULTS, exist_ok=True)
    syms = {v: assemble(v, *VARIANTS[v][:3]) for v in VARIANTS}
    hs = syms["Crst_C000"]
    for v in VARIANTS:       # helpers are form-independent: same addresses in every build
        assert all(syms[v][h] == hs[h] for h in ("H_LDL", "H_STL", "H_ENTER", "H_LEAVE", "H_LDI", "H_STI"))
    cfgs = {
        "v2ref": V2REF,
        "rst": make_rom("rst", {0x08: "H_LDL", 0x10: "H_STL", 0x18: "H_ENTER", 0x20: "H_LEAVE",
                                0x28: "H_LDI", 0x30: "H_STI"}, hs),
        "disp": make_rom("disp", {0x08: "H_LDL", 0x10: "H_STL", 0x18: "H_ENTER", 0x20: "H_LEAVE",
                                  0x28: "H_NOP", 0x30: "H_DISPATCH"}, hs),
    }
    out = {"sizes": {}, "helpers": {}, "cases": {}, "micro": {}, "basic": {}}
    resf = os.path.join(RESULTS, "spike_results.json")
    if a.micro_only and os.path.exists(resf):
        out = json.load(open(resf))
    for v, s in syms.items():
        out["sizes"][v] = {fn: s[fn + "_END"] - s[fn] for fn in ("SUM", "COPY", "ASUM", "MOVE", "FACT")}
    for h in ("H_LDL", "H_STL", "H_ENTER", "H_LEAVE", "H_LDI", "H_STI", "H_CMPLT", "H_DISPATCH"):
        out["helpers"][h] = hs[h + "_END"] - hs[h]
    out["helpers"]["all"] = hs["HELPERS_END"] - hs["H_LDL"]
    out["frame_fn_bytes"] = {k: hs[k + "_END"] - hs[k] for k in ("EL_A", "EL_C_CALL", "EL_C_RST")}
    port = a.port
    for cfg, path in cfgs.items():
        m = Machine(path, port, label=cfg).start()
        port += 1
        try:
            run = Runner(m)
            print("== ROM config %s: booted to IO_READ_KEY" % cfg, flush=True)
            for v, (form, hmode, base, vc) in VARIANTS.items():
                if vc != cfg or a.micro_only:
                    continue
                for cid, _, _ in CASES:
                    for ei in ((True,) if cid == "soak" else (False, True)):
                        if cid == "soak" and v not in ("Crst_C000", "Ccall_C000"):
                            continue
                        r = run.case(v, syms[v], cid, ei=ei, budget=40_000_000 if cid == "soak" else 6_000_000)
                        r["correct"] = run.verify(cid, syms[v], r, base)
                        out["cases"]["%s/%s/%s" % (v, cid, "ei" if ei else "di")] = r
                        print("%-11s %-7s %s t=%9d stack=%s ok=%s correct=%s frames=%d depth=%d" % (
                            v, cid, "ei" if ei else "di", r["t"], r["stack"], r["ok_run"], r["correct"],
                            r["frames"], r["depth_after"]), flush=True)
                if base >= 0xC000 and cfg == "v2ref" and form == 1:
                    r = run.case(v, syms[v], "hazard", ei=True, budget=3_000_000)
                    r.pop("vdata", None)
                    r["program_code_ran"] = r["result"] == 0x1234
                    out["cases"]["%s/hazard/ei" % v] = r
                    print("hazard: returned=%s HL=%04X (program code ran: %s) depth=%d" % (
                        r["ok_run"], r["result"], r["program_code_ran"], r["depth_after"]))
            vm = {"v2ref": "Ccall_C000", "rst": "Crst_C000", "disp": "Crst_C000"}[cfg]
            for mid, code, valid in MICRO:
                if cfg in valid:
                    r = run.micro(vm, syms[vm], mid)
                    out["micro"][mid] = r
                    print("micro %-13s t=%4d bytes=%d ok=%s" % (mid, r["t"], r["bytes"], r["ok"]), flush=True)
            if cfg == "v2ref" and not a.micro_only:
                for bid, (setup, full, expect) in BASIC.items():
                    r = basic_run(m, full)
                    vals = [v for _, v in m.scalars(8)]
                    if bid == "copy":
                        r["correct"] = m.read(28928, 256) == bytes((i * 7 + 0x5A) & 0xFF for i in range(256))
                    elif bid == "move":     # untimed check run: same program + a checksum of y()
                        basic_run(m, full + ["c = 0", "FOR i = 0 TO 19", "c = c + y(i)", "NEXT i"])
                        r["correct"] = sum(i + 3 for i in range(N_PTS)) in [v for _, v in m.scalars(8)]
                    else:
                        r["correct"] = expect in vals
                    if setup:
                        r0 = basic_run(m, setup)
                        r["t_setup_run"] = r0["t_run"]
                        r["t_loop"] = r["t_run"] - r0["t_run"]
                    else:
                        r["t_loop"] = r["t_run"]
                    out["basic"][bid] = r
                    print("BASIC %-6s compile=%d run=%d loop=%d clean=%s correct=%s" % (
                        bid, r["t_compile"], r["t_run"], r["t_loop"], r["clean"], r["correct"]), flush=True)
        finally:
            m.stop()
    json.dump(out, open(os.path.join(RESULTS, "spike_results.json"), "w"), indent=1, sort_keys=True)
    print("sizes", json.dumps(out["sizes"]))
    print("helpers", json.dumps(out["helpers"]), "frame fns", json.dumps(out["frame_fn_bytes"]))


if __name__ == "__main__":
    main()
